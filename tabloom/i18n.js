  const DICTIONARIES = { en, zh };
  const FALLBACK = "en";

  function normalizeLanguage(value) {
    return value === "en" || value === "zh" ? value : "system";
  }

  // The browser's own UI language, which is what "system" means here.
  function systemLanguage() {
    let tag = "";
    try {
      tag = String(globalThis.chrome?.i18n?.getUILanguage?.() || navigator?.language || "");
    } catch {
      tag = "";
    }
    return tag.toLowerCase().startsWith("zh") ? "zh" : "en";
  }

  function resolveLanguage(setting) {
    const normalized = normalizeLanguage(setting);
    return normalized === "system" ? systemLanguage() : normalized;
  }

  function translate(language, key, values) {
    const dictionary = DICTIONARIES[language] || DICTIONARIES[FALLBACK];
    const entry = dictionary[key] ?? DICTIONARIES[FALLBACK][key];
    if (entry === undefined) return key;
    if (typeof entry === "function") return entry(values || {});
    return String(entry).replace(/\{(\w+)\}/g, (match, name) => (
      values && name in values ? String(values[name]) : match
    ));
  }

  globalThis.TabloomI18n = {
    dictionaries: DICTIONARIES,
    languages: ["system", "en", "zh"],
    normalizeLanguage,
    resolveLanguage,
    systemLanguage,
    translate
  };
